import { test, expect } from "@playwright/test";
import { fileURLToPath } from "node:url";

test.use({ channel: process.env.RESOURCE_BROWSER_CHANNEL || undefined, headless: !process.env.RESOURCE_HEADED });
const archive = fileURLToPath(new URL("../../blueprint input/mechanica-input-package.zip", import.meta.url));

test("reviewed email matches the stored enquiry and approval, on desktop and mobile", async ({ page }, info) => {
  test.setTimeout(150_000);
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await page.locator('input[type="file"]').first().setInputFiles(archive);
  await page.locator(".rs-risk-needs").getByLabel("Delivery destination").fill("Bristol, UK");
  await page.locator(".rs-risk-needs").getByLabel("Need-by date").fill("2027-01-05");
  await page.getByRole("button", { name: "Confirm parts and scan supply risk", exact: true }).click();
  await expect(page.locator(".rs-part-source")).toHaveCount(0);
  await page.getByRole("button", { name: "Expand Fan blades", exact: true }).click();
  await page.getByRole("button", { name: /^Fan blade 03\s*Arrival unknown$/ }).click();
  await page.locator(".rs-risk-panel").getByRole("button", { name: "Find alternative suppliers", exact: true }).click();
  await page.getByLabel("Quantity", { exact: true }).fill("3");
  await page.getByLabel("Required on site by", { exact: true }).fill("2027-01-05");
  await page.getByRole("button", { name: "Find suppliers", exact: true }).click();
  await page.getByRole("button", { name: "Compare shortlist", exact: true }).click();
  const response = page.waitForResponse(r => r.url().endsWith("/package") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Select supplier", exact: true }).click();
  const stored = await (await response).json();
  const item = stored.package.items[0];
  expect(item.quantity).toBe(3);
  expect(stored.package.enquiry.required_by).toBe("2027-01-05");
  expect(stored.package.enquiry.delivery_destination).toBe("Bristol, UK");
  expect(item.rfq_text).toContain("Bristol, UK");
  expect(item.rfq_text).toContain("Selected assembly item: Fan blade 03");
  expect(item.rfq_text).toContain("5 January 2027");
  const email = page.getByRole("article", { name: "Request for quotation" });
  await expect(email.locator(".rs-email-body")).toHaveText(item.rfq_text);
  await expect(email.locator(".rs-email-envelope")).toContainText(item.rfq_subject);
  await expect(page.locator(".rs-fulfil")).toHaveCSS("opacity", "1");
  await page.getByRole("button", { name: "Scene", exact: true }).click();
  expect(await email.evaluate(el => getComputedStyle(el, "::before").content)).toBe("none");
  await expect(page.locator(".fl-pane")).toBeHidden();
  await page.screenshot({ path: info.outputPath("supplier-email-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator(".rs-fulfil-main").evaluate(el => { el.scrollTop = 0; });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("supplier-email-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole("checkbox").check();
  const approvalResponse = page.waitForResponse(r => r.url().endsWith("/package/approve"));
  await page.getByRole("button", { name: "Approve enquiry", exact: true }).click();
  const approved = await (await approvalResponse).json();
  expect(approved.package.package_id).toBe(stored.package.package_id);
  expect(approved.package.items[0].rfq_text).toBe(item.rfq_text);
  await expect(page.getByRole("button", { name: "Send enquiry (simulated)", exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
